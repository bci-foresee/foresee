static float filterloop(uint16_t next_input_value, float* xv, float* yv, double* filter_vals, double gain)
{ 
    { 
        xv[0] = xv[1];
        xv[1] = xv[2];
        xv[2] = xv[3];
        xv[3] = xv[4];
        xv[4] = xv[5];
        xv[5] = xv[6];
        xv[6] = xv[7];
        xv[7] = xv[8];
        xv[8] = xv[9];
        xv[9] = xv[10];
        xv[10] = next_input_value / gain;
        yv[0] = yv[1];
        yv[1] = yv[2];
        yv[2] = yv[3];
        yv[3] = yv[4];
        yv[4] = yv[5];
        yv[5] = yv[6];
        yv[6] = yv[7];
        yv[7] = yv[8];
        yv[8] = yv[9];
        yv[9] = yv[10];
        yv[10] =   (xv[10] - xv[0]) + 5 * (xv[2] - xv[8]) + 10 * (xv[6] - xv[4])
            + (filter_vals[0] * yv[0]) + (filter_vals[1] * yv[1])
            + (filter_vals[2] * yv[2]) + (filter_vals[3] * yv[3])
            + (filter_vals[4] * yv[4]) + (filter_vals[5] * yv[5])
            + (filter_vals[6] * yv[6]) + (filter_vals[7] * yv[7])
            + (filter_vals[8] * yv[8]) + (filter_vals[9] * yv[9]);
        return yv[10];
    }
}

