        //printf("filter_vals: %f %f %f %f %f %f %f %f %f %f\n", filter_vals[0], filter_vals[1], filter_vals[2], filter_vals[3], filter_vals[4], filter_vals[5], filter_vals[6], filter_vals[7], filter_vals[8], filter_vals[9]);

        float sum = 0;
